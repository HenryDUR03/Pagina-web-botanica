-- 01_schema.sql
-- Esquema base de la tienda de plantas.
-- Ejecuta este archivo primero, en el SQL Editor de Supabase.

-- Categorías del catálogo (semillas, plantas, materas y abono).
create table if not exists public.categorias (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  slug text not null unique
);

comment on table public.categorias is 'Categorías visibles en el catálogo.';

-- Productos. Los precios se guardan en pesos colombianos (enteros, sin centavos).
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  categoria_id bigint not null references public.categorias (id) on delete restrict,
  nombre text not null,
  descripcion text not null default '',
  precio integer not null check (precio >= 0),
  stock integer not null default 0 check (stock >= 0),
  imagen_url text not null default '',
  cuidados jsonb check (cuidados is null or jsonb_typeof(cuidados) = 'object'),
  creado_en timestamptz not null default now()
);

comment on table public.productos is 'Catálogo de productos de la tienda.';
comment on column public.productos.cuidados is 'Ficha opcional de cuidados: luz, riego y tamaño.';

create index if not exists productos_categoria_idx on public.productos (categoria_id);
create index if not exists productos_nombre_idx on public.productos (lower(nombre));

-- Pedidos. No se guarda ningún dato de tarjeta: el pago es simulado.
create table if not exists public.pedidos (
  id bigint generated by default as identity primary key,
  numero_pedido text not null unique,
  nombre_cliente text not null,
  correo text not null,
  telefono text not null,
  direccion text not null,
  ciudad text not null,
  metodo_pago text not null default 'tarjeta_simulada',
  subtotal integer not null check (subtotal >= 0),
  descuento integer not null default 0 check (descuento >= 0),
  envio integer not null default 0 check (envio >= 0),
  cupon text,
  total integer not null check (total >= 0),
  estado text not null default 'confirmado'
    check (estado in ('confirmado', 'preparando', 'enviado', 'entregado')),
  creado_en timestamptz not null default now()
);

comment on table public.pedidos is 'Pedidos creados desde el checkout simulado.';
comment on column public.pedidos.cupon is 'Código de cupón aplicado, si existe.';

create index if not exists pedidos_correo_idx on public.pedidos (lower(correo));
create index if not exists pedidos_creado_en_idx on public.pedidos (creado_en desc);

-- Líneas del pedido. Se guarda el precio del momento de la compra.
create table if not exists public.pedido_items (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references public.pedidos (id) on delete cascade,
  producto_id bigint not null references public.productos (id) on delete restrict,
  cantidad integer not null check (cantidad > 0 and cantidad <= 99),
  precio_unitario integer not null check (precio_unitario >= 0)
);

comment on table public.pedido_items is 'Productos y cantidades de cada pedido.';

create index if not exists pedido_items_pedido_idx on public.pedido_items (pedido_id);
